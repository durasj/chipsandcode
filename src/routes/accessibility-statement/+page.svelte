  <section>
    <h2>Navigation and interaction</h2>
    <p>
      The main navigation is always Learn, Tools, and About. A skip link moves past it. Buttons,
      switches, circuit connections, and tool inputs have keyboard controls and visible focus.
      Connection menus offer an alternative to selecting pins on a circuit diagram.
    </p>
    <p>
      Signals show values and labels as well as color. Text uses explicit foreground and background
      colors. Your operating system’s reduced-motion preference replaces the scrolling computer
      animation with a static sequence.
    </p>
  </section>
  <section>
    <h2>Reading, code, and media</h2>
    <p>
      Short explanations link to full reading in the same interface. Layouts reflow on narrow
      screens; code and wide circuit diagrams can scroll inside their own panels. The introduction
      film has captions and a text transcript.
    </p>
    <p>
      The Hardware simulator uses Monaco Editor. Its editor help is available from the Help
      disclosure. Standard text fields in the guided workspace provide another way to write HDL.
    </p>
  </section>
  <section>
    <h2>Checks and feedback</h2>
    <p>
      We use automated accessibility checks alongside keyboard, responsive-layout, and contrast
      reviews. These checks do not cover every assistive technology or replace feedback from people
      using the site.
    </p>
    <p>
      If a control, explanation, or diagram gets in your way, <a
        href="https://github.com/durasj/chipsandcode/issues">report an accessibility issue</a
      >. Include the page, what you were trying to do, and your browser or assistive technology if
      you can.
    </p>
    <p>
      <a href="https://mcmw.abilitynet.org.uk/">AbilityNet’s My Computer My Way</a> provides guidance
      on adapting your device to your needs.
    </p>
  </section>
